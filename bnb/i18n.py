def normalise(locale: str | None) -> str:
    """'pt-BR' and 'PT_br' both mean the Portuguese bundle."""
    if not locale:
        return "en"
    base = str(locale).replace("_", "-").split("-")[0].lower()
    return base if base in STRINGS else "en"


def bundle(locale: str | None) -> dict:
    """Strings for a locale, with English filling any gap.

    Falling back key-by-key rather than wholesale means a half-finished
    translation ships useful coverage instead of nothing.
    """
    code = normalise(locale)
    strings = dict(STRINGS["en"])
    strings.update(STRINGS.get(code, {}))
    return {
        "locale": code,
        "dir": "rtl" if code in RTL else "ltr",
        "languages": LANGUAGES,
        "strings": strings,
    }


def missing_keys() -> dict[str, list[str]]:
    """Translation debt, so it can be asserted on in CI rather than discovered
    by a user who suddenly sees English."""
    english = set(STRINGS["en"])
    return {code: sorted(english - set(strings))
            for code, strings in STRINGS.items() if english - set(strings)}
